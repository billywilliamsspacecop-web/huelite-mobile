import { defineConfig } from "vite";
import { createHash } from "node:crypto";

// Emits sw.js at build time with the exact list of built files, so the app
// opens offline after the first visit. The cache name is a hash of the
// build, so a new deploy replaces the old files cleanly.
function offlineWorker() {
  return {
    name: "huelite-offline-worker",
    apply: "build",
    generateBundle(_, bundle) {
      const files = Object.keys(bundle);
      const extras = ["manifest.webmanifest", "icon-192.png", "icon-512.png",
                      "icon-maskable-512.png", "apple-touch-icon.png"];
      const hash = createHash("sha1");
      for (const f of files) {
        const item = bundle[f];
        hash.update(f).update(item.type === "chunk" ? item.code : item.source);
      }
      const version = hash.digest("hex").slice(0, 10);
      const list = ["./", ...files, ...extras];
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: `// generated by vite.config.js - do not edit
const CACHE = "huelite-${version}";
const FILES = ${JSON.stringify(list)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("huelite-") && k !== CACHE)
        .map((k) => caches.delete(k))))
      .then(() => self.clients.claim()));
});

// Files are cache-first (they are versioned by name); the page itself is
// network-first so a new deploy shows up on the next visit with signal.
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  if (req.mode === "navigate") {
    e.respondWith(
      fetch(req).then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put("./", copy));
        return res;
      }).catch(() => caches.match("./", { ignoreVary: true })));
    return;
  }
  // ignoreVary: module scripts send an Origin header the install-time
  // request did not, and a server's "Vary: Origin" would otherwise miss
  e.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`,
      });
    },
  };
}

// Relative base so the built files load from Capacitor's local file server,
// from a GitHub Pages sub-path, or from any static host.
export default defineConfig({
  base: "./",
  build: { target: "es2020", outDir: "dist" },
  plugins: [offlineWorker()],
});
